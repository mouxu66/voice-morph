norm = lambda s: re.sub(r"\s+", "", s)
LOOKUP = {norm(o): n for o, n in REPLACES}


def set_para_text(para, text: str) -> None:
    runs = para.runs
    if not runs:
        return
    runs[0].text = text
    for r in runs[1:]:
        r.text = ""


def iter_paras(shapes):
    for sh in shapes:
        if sh.has_text_frame:
            for para in sh.text_frame.paragraphs:
                yield para
        if sh.has_table:
            for row in sh.table.rows:
                for cell in row.cells:
                    for para in cell.text_frame.paragraphs:
                        yield para


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError, ValueError):
        pass
    prs = Presentation(str(PPTX))
    hit = set()
    for si, slide in enumerate(prs.slides, 1):
        for para in iter_paras(slide.shapes):
            full = "".join(r.text for r in para.runs)
            if not full.strip():
                continue
            new = LOOKUP.get(norm(full))
            if new is not None and new != full:
                set_para_text(para, new)
                hit.add(norm(new))
    prs.save(str(PPTX))
    missed = [(o[:30]) for o, n in REPLACES if norm(n) not in hit]
    print(f"命中 {len(hit)}/{len(REPLACES)} 条")
    if missed:
        print("⚠️ 未命中：")
        for m in missed:
            print("  -", m)
    return 0 if not missed else 1


if __name__ == "__main__":
    sys.exit(main())
