def set_para_text(p: Paragraph, text: str) -> None:
    """重写段落文本：按 **bold** 分段生成 runs，字体继承原第一个 run。"""
    proto = None
    for r in p.runs:
        if r.text.strip():
            proto = r
            break
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        run = p.add_run(seg)
        if i % 2 == 1:
            run.bold = True
        if proto is not None:
            run.font.name = proto.font.name
            run.font.size = proto.font.size
            # 东亚字体名需单独设置，否则中文回退宋体默认
            rPr = run._element.get_or_add_rPr()
            from docx.oxml.ns import qn
            rFonts = rPr.find(qn("w:rFonts"))
            if rFonts is None:
                rFonts = rPr.makeelement(qn("w:rFonts"), {})
                rPr.append(rFonts)
            src = proto._element.find(qn("w:rPr"))
            if src is not None:
                src_fonts = src.find(qn("w:rFonts"))
                if src_fonts is not None:
                    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia"):
                        val = src_fonts.get(qn(attr))
                        if val:
                            rFonts.set(qn(attr), val)


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except (AttributeError, OSError, ValueError):
        pass
    doc = Document(str(DOCX))
    missed = []

    # 1+2. 正文段落
    n_del = n_rep = 0
    for p in doc.paragraphs:
        t = p.text.strip()
        if not t:
            continue
        if any(t.startswith(pref) for pref in DELETE_PREFIXES):
            p._element.getparent().remove(p._element)
            n_del += 1
            continue
        for pref, new in REPLACE_PARAS:
            if t.startswith(pref):
                set_para_text(p, new)
                n_rep += 1
                break

    # 3. 表格 cell
    n_cell = 0
    for ti, table in enumerate(doc.tables):
        for (r, c), new in REPLACE_CELLS.get(ti, {}).items():
            try:
                cell = table.rows[r].cells[c]
            except IndexError:
                missed.append(f"T{ti}R{r}C{c} 越界")
                continue
            set_para_text(cell.paragraphs[0], new)
            for extra in cell.paragraphs[1:]:
                extra._element.getparent().remove(extra._element)
            n_cell += 1

    # 4. 删表行
    n_row = 0
    for ti, kw in DELETE_ROWS:
        for row in list(doc.tables[ti].rows):
            if kw in row.cells[0].text:
                row._element.getparent().remove(row._element)
                n_row += 1
                break

    doc.save(str(DOCX))
    print(f"删段 {n_del} · 改段 {n_rep} · 改格 {n_cell} · 删行 {n_row}")
    print(f"替换表总数 {len(REPLACE_PARAS)} 条，未命中 {len(REPLACE_PARAS) - n_rep} 条")
    if missed:
        print("⚠️ 未命中/越界：", missed)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
